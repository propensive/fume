package fume

import soundness.*

// The invocation point, alone in its own build module. `externalize` (from burdock, re-exported
// through `soundness.*`) records the SHA-256 of every jar on THIS module's compile classpath into
// `META-INF/burdock.deps` at compile time. Because the `launcher` module depends on `fume-client`
// as a PUBLISHED Maven Central artifact (see `build.mill`), the exact jar bytes on the classpath
// match the published ones, so `soundness.repackage` resolves it via deps.dev and rewrites it into
// an on-demand `Burdock-Require` download rather than inlining its classes. The whole command
// dispatch lives in `fume.runClient` in the (published) `client` module.
@main
def fume(): Unit = externalize(runClient())
